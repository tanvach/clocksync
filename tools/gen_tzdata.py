#!/usr/bin/env python3
"""Generate tzdata.h: IANA zone names mapped to POSIX TZ strings.

The ESP32 C library only understands POSIX TZ strings, so the firmware ships
this table and the web UI lets you pick a zone by name. The POSIX string is
the footer line of each compiled TZif file (RFC 8536, version 2+).

Usage: python3 tools/gen_tzdata.py [zoneinfo_dir] > tzdata.h
"""
import os
import re
import sys

# Negative transition times (e.g. Greenland's "M3.5.0/-1", i.e. 23:00 the
# evening before) are a POSIX extension that newlib parses as unsigned and
# gets badly wrong. Clamp them to 00:00: the switch then happens up to a few
# hours late, once a year, instead of never.
NEGATIVE_TIME = re.compile(r"/-[0-9]+(:[0-9]+){0,2}")


def posix_footer(path):
    with open(path, "rb") as f:
        data = f.read()
    if not data.startswith(b"TZif") or data[4:5] < b"2":
        raise ValueError(f"{path}: not a TZif v2+ file")
    footer = data.rstrip(b"\n").rsplit(b"\n", 1)[1].decode("ascii")
    if not footer:
        raise ValueError(f"{path}: empty POSIX footer")
    return footer


def main():
    zoneinfo = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
    names = {"UTC"}
    with open(os.path.join(zoneinfo, "zone.tab"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            names.add(line.split("\t")[2].strip())
    version = "unknown"
    vpath = os.path.join(zoneinfo, "+VERSION")
    if os.path.exists(vpath):
        version = open(vpath, encoding="ascii").read().strip()

    rows = []
    for name in sorted(names):
        footer = NEGATIVE_TIME.sub("/0", posix_footer(os.path.join(zoneinfo, name)))
        if "\t" in footer or '"' in footer or "\\" in footer:
            raise ValueError(f"{name}: unexpected characters in {footer!r}")
        rows.append((name, footer))

    out = sys.stdout
    out.write("// Generated by tools/gen_tzdata.py from IANA tzdata %s. Do not edit.\n" % version)
    out.write("// One zone per line: \"<IANA name>\\t<POSIX TZ string>\\n\".\n")
    out.write("#pragma once\n\n")
    out.write("#ifndef PROGMEM\n#define PROGMEM\n#endif\n\n")
    out.write('#define TZDATA_VERSION "%s"\n#define TZDATA_COUNT %d\n\n' % (version, len(rows)))
    out.write("static const char TZDATA[] PROGMEM =\n")
    for name, footer in rows:
        out.write('  "%s\\t%s\\n"\n' % (name, footer))
    out.write("  ;\n")


if __name__ == "__main__":
    main()
